export class I18n {
    constructor(defaultLang = 'en-US') {
        this.lang = defaultLang;
        this.listeners = [];
    }

    setLanguage(lang) {
        if (TRANSLATIONS[lang]) {
            this.lang = lang;
            this.notifyListeners();
        }
    }

    t(key, variables = {}) {
        let text = key;
        // 1. Try current language
        if (TRANSLATIONS[this.lang] && TRANSLATIONS[this.lang][key]) {
            text = TRANSLATIONS[this.lang][key];
        }
        // 2. Fallback to English
        else if (this.lang !== 'en-US' && TRANSLATIONS['en-US'] && TRANSLATIONS['en-US'][key]) {
            text = TRANSLATIONS['en-US'][key];
        }

        // 3. Replace variables if provided
        if (variables && typeof variables === 'object') {
            Object.keys(variables).forEach(varKey => {
                text = text.replace(new RegExp(`\\{${varKey}\\}`, 'g'), variables[varKey]);
            });
        }

        return text;
    }

    // Get translation for a specific language (useful for constants initialization)
    tFor(lang, key) {
        return TRANSLATIONS[lang][key] || key;
    }

    subscribe(listener) {
        this.listeners.push(listener);
    }

    notifyListeners() {
        this.listeners.forEach(listener => listener(this.lang));
    }
    // Sync language from host app settings
    sync() {
        const htmlLang = document.documentElement.lang;
        const mappedHtml = mapLanguage(htmlLang);
        if (mappedHtml && mappedHtml !== this.lang) {
            this.setLanguage(mappedHtml);
        }
    }
}

// Helper to map various language strings to our supported keys
function mapLanguage(lang) {
    if (!lang) return null;
    const l = lang.toLowerCase();

    // Traditional Chinese
    if (l === 'zh-tw' || l === 'zh-hk' || l.includes('hant')) {
        return 'zh-TW';
    }
    // Simplified Chinese
    if (l.startsWith('zh')) {
        return 'zh-CN';
    }
    // Other supported languages
    if (l.startsWith('ru')) return 'ru';
    if (l.startsWith('ko')) return 'ko';
    if (l.startsWith('fr')) return 'fr';
    if (l.startsWith('es')) return 'es';
    if (l.startsWith('nl')) return 'nl';
    if (l.startsWith('de')) return 'de';
    if (l.startsWith('el')) return 'el';
    if (l.startsWith('ja')) return 'ja-JP';
    if (l.startsWith('en')) return 'en-US';

    return null;
}

// Helper to determine initial language
function getInitialLanguage() {
    // 1. Check document.documentElement.lang (Host app preference)
    const htmlLang = document.documentElement.lang;
    const mappedHtml = mapLanguage(htmlLang);
    if (mappedHtml) return mappedHtml;

    // 2. Check navigator.language (Browser preference)
    const browserLang = navigator.language;
    const mappedBrowser = mapLanguage(browserLang);
    if (mappedBrowser) return mappedBrowser;

    // 3. Default fallback to English
    return 'en-US';
}

export const i18n = new I18n(getInitialLanguage());
